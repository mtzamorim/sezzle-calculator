// Supplemental checks of the actual compiled production modules, not a Vitest/React run.
// Usage: node core-runtime-check.cjs /absolute/path/to/compiled-core
const assert = require('node:assert/strict')
const { join } = require('node:path')
const { test } = require('node:test')
const root = process.argv[2]
if (!root) throw new Error('Pass the directory generated by the documented TypeScript core-only compilation.')
const { calculate, CalculatorApiError, REQUEST_TIMEOUT_MS } = require(join(root, 'api/calculator.js'))
const { validateInputs } = require(join(root, 'domain/validation.js'))
const { formatNumber, formatExpression } = require(join(root, 'domain/format.js'))
const cases = [
  [{ operation: 'add', a: 2, b: 3 }, 5], [{ operation: 'subtract', a: 7, b: 9 }, -2],
  [{ operation: 'multiply', a: 2.5, b: -4 }, -10], [{ operation: 'divide', a: 7, b: 2 }, 3.5],
  [{ operation: 'power', a: 2, b: -3 }, 0.125], [{ operation: 'sqrt', a: 81 }, 9],
  [{ operation: 'percent', a: 15, b: 200 }, 30],
]
const base = process.env.API_URL ?? 'http://127.0.0.1:8080'
const liveFetch = (path, init) => fetch(`${base}${path}`, init)
for (const [input, result] of cases) {
  test(`real TypeScript client -> real Go API: ${input.operation}`, async () => {
    assert.deepEqual(await calculate(input, { fetcher: liveFetch }), { ...input, result })
  })
}
for (const raw of ['', ' ', 'abc', '0x10', '1,2', '1_000', 'NaN', 'Infinity', '1e999', '1e', '--1']) {
  test(`validation rejects ${JSON.stringify(raw)}`, () => assert.equal(validateInputs('add', raw, '2').valid, false))
}
for (const [raw, value] of [[' -1.2 ', -1.2], ['+.5', .5], ['1e2', 100], ['0', 0]]) {
  test(`validation accepts ${JSON.stringify(raw)}`, () => assert.deepEqual(validateInputs('add', raw, '2'), { valid: true, input: { operation: 'add', a: value, b: 2 } }))
}
test('unary, zero-division and negative-root validation', () => {
  assert.deepEqual(validateInputs('sqrt', '9', 'garbage'), { valid: true, input: { operation: 'sqrt', a: 9 } })
  assert.equal(validateInputs('sqrt', '-1', '').valid, false)
  assert.equal(validateInputs('divide', '1', '-0').valid, false)
  assert.equal(validateInputs('add', '1', '').valid, false)
})
test('display formatting and expression labels', () => {
  assert.equal(formatNumber(-0), '0'); assert.equal(formatNumber(0.1 + 0.2), '0.3')
  assert.equal(formatNumber(1e-12), '1.000000e-12'); assert.equal(formatNumber(1e12), '1.000000e+12')
  assert.equal(formatExpression('percent', 15, 200), '15% of 200')
  assert.equal(formatExpression('power', 2, 3), '2 ^ 3')
})
const input = { operation: 'add', a: 2, b: 3 }
const invalid = [null, [], {}, { ...input, operation: 'unknown', result: 5 }, { ...input, operation: 'subtract', result: 5 },
  { ...input, a: 99, result: 5 }, { ...input, b: 99, result: 5 }, { ...input, result: '5' }, { ...input, result: Infinity }]
for (const [index, payload] of invalid.entries()) {
  test(`response contract rejects malformed/mismatched payload ${index + 1}`, async () => {
    await assert.rejects(calculate(input, { fetcher: async () => ({ ok: true, status: 200, json: async () => payload }) }), { code: 'invalid_response' })
  })
}
test('real backend math error preserves status and message', async () => {
  await assert.rejects(calculate({ operation: 'divide', a: 1, b: 0 }, { fetcher: liveFetch }), { code: 'math_error', status: 422, message: 'Division by zero is not allowed.' })
})
test('network failure is mapped without leaking implementation details', async () => {
  await assert.rejects(calculate(input, { fetcher: async () => { throw new Error('private host detail') } }), { code: 'network_error', status: 0 })
})
test('unreadable server body is rejected', async () => {
  await assert.rejects(calculate(input, { fetcher: async () => ({ status: 502, json: async () => { throw new SyntaxError('bad JSON') } }) }), { code: 'invalid_response', status: 502 })
})
test('already-cancelled request never starts transport', async () => {
  const controller = new AbortController(); controller.abort()
  await assert.rejects(calculate(input, { signal: controller.signal, fetcher: async () => { assert.fail('transport called') } }), { code: 'cancelled' })
})
test('active cancellation reaches the transport', async () => {
  const controller = new AbortController()
  let requestSignal
  const pending = calculate(input, { signal: controller.signal, fetcher: (_url, options) => new Promise((_resolve, reject) => {
    requestSignal = options.signal
    options.signal.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')), { once: true })
  }) })
  controller.abort()
  await assert.rejects(pending, { code: 'cancelled' }); assert.equal(requestSignal.aborted, true)
})
test('cancelled transport cannot publish a late successful response', async () => {
  const controller = new AbortController()
  await assert.rejects(calculate(input, { signal: controller.signal, fetcher: async () => {
    controller.abort()
    return { ok: true, status: 200, json: async () => ({ ...input, result: 5 }) }
  } }), { code: 'cancelled' })
})
test('timeout also bounds a delayed response body (real 10-second timer)', async () => {
  const started = performance.now()
  const pending = calculate(input, { fetcher: async (_url, options) => ({ ok: true, status: 200,
    json: () => new Promise((_resolve, reject) => options.signal.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')), { once: true })),
  }) })
  await assert.rejects(pending, { code: 'timeout', status: 0 })
  assert.ok(performance.now() - started >= REQUEST_TIMEOUT_MS - 100)
})
test('the public API error remains identifiable', () => assert.ok(new CalculatorApiError('x', 'message', 400) instanceof Error))
